/**
 * The prompt library's file format, vocabulary and checks. Pure and dependency-free so that
 * the app, the tests AND `scripts/prompts-to-sql.mjs` (Node runs this file directly) share one source.
 * Keep this file to erasable TypeScript (no enums, no parameter properties).
 *
 * File: supabase/seed/prompts.json, an array of
 *   { "text": "...", "depth": "light|medium|deep", "mood"?: ..., "time_of_day"?: ..., "track_hint"?: ... }
 * A missing mood / time_of_day / track_hint means "fits any".
 */
export const DEPTHS = ['light', 'medium', 'deep'] as const
export const MOODS = ['calm', 'heavy', 'restless', 'grateful', 'hopeful', 'curious'] as const
export const TIMES = ['morning', 'afternoon', 'evening', 'night'] as const
export const TRACK_HINTS = ['daily', 'spiritual', 'letters', 'dreams'] as const

export type Depth = (typeof DEPTHS)[number]
export type Mood = (typeof MOODS)[number]
export type TimeOfDay = (typeof TIMES)[number]
export type TrackHint = (typeof TRACK_HINTS)[number]

export type SeedPrompt = {
  text: string
  depth: Depth
  mood: Mood | null
  time_of_day: TimeOfDay | null
  track_hint: TrackHint | null
}

export const MIN_LEN = 12
export const MAX_LEN = 240
export const WARN_LEN = 160

const KEYS = new Set(['text', 'depth', 'mood', 'time_of_day', 'track_hint', 'language'])
const EMOJI = /\p{Extended_Pictographic}/u

const norm = (s: string) => s.replace(/\s+/gu, ' ').trim()

export type SeedReport = { prompts: SeedPrompt[]; errors: string[]; warnings: string[] }

export function validateSeed(raw: unknown): SeedReport {
  const errors: string[] = []
  const warnings: string[] = []
  const prompts: SeedPrompt[] = []
  const list = Array.isArray(raw) ? raw : (raw as { prompts?: unknown } | null)?.prompts
  if (!Array.isArray(list)) {
    return { prompts, errors: ['The file must be a list of prompts: [ { "text": ..., "depth": ... }, ... ]'], warnings }
  }
  const seen = new Map<string, number>()
  list.forEach((item, i) => {
    const at = `#${i + 1}`
    const before = errors.length
    if (!item || typeof item !== 'object' || Array.isArray(item)) return void errors.push(`${at}: each prompt must be an object.`)
    const o = item as Record<string, unknown>
    const bad = Object.keys(o).filter((k) => !KEYS.has(k))
    if (bad.length) errors.push(`${at}: unknown field${bad.length > 1 ? 's' : ''} ${bad.map((k) => `"${k}"`).join(', ')}. Allowed: text, depth, mood, time_of_day, track_hint.`)
    if (o.language !== undefined && o.language !== 'en') errors.push(`${at}: v1 prompts are English only ("language" must be "en" or left out).`)

    const text = typeof o.text === 'string' ? norm(o.text) : ''
    if (typeof o.text !== 'string' || !text) errors.push(`${at}: "text" is missing.`)
    else {
      const label = `${at} ("${text.slice(0, 40)}${text.length > 40 ? '…' : ''}")`
      if (text.length < MIN_LEN) errors.push(`${label}: too short (${text.length} characters; at least ${MIN_LEN}).`)
      if (text.length > MAX_LEN) errors.push(`${label}: too long (${text.length} characters; at most ${MAX_LEN}).`)
      else if (text.length > WARN_LEN) warnings.push(`${label}: ${text.length} characters is long for a prompt. Shorter ones read better on the page.`)
      if (EMOJI.test(text)) errors.push(`${label}: no emoji, please.`)
      const key = text.toLowerCase()
      if (seen.has(key)) errors.push(`${label}: same text as #${seen.get(key)}.`)
      else seen.set(key, i + 1)
    }

    const pick = <T extends string>(field: string, allowed: readonly T[], required: boolean): T | null => {
      const v = o[field]
      if (v === undefined || v === null || v === '') {
        if (required) errors.push(`${at}: "${field}" is required (${allowed.join(' / ')}).`)
        return null
      }
      if (typeof v !== 'string' || !(allowed as readonly string[]).includes(v)) {
        errors.push(`${at}: "${field}" is "${String(v)}". Use one of: ${allowed.join(', ')}.`)
        return null
      }
      return v as T
    }
    const depth = pick('depth', DEPTHS, true)
    const mood = pick('mood', MOODS, false)
    const time_of_day = pick('time_of_day', TIMES, false)
    const track_hint = pick('track_hint', TRACK_HINTS, false)
    if (text && depth && errors.length === before) prompts.push({ text, depth, mood, time_of_day, track_hint })
  })
  if (list.length === 0) warnings.push('The file is empty.')
  return { prompts, errors, warnings }
}

const q = (v: string | null) => (v === null ? 'null' : `'${v.replace(/\u0000/g, '').replace(/'/g, "''")}'`)

/** An idempotent SQL file: running it again updates tags on prompts that already exist (matched by their text) and adds the new ones. It never deletes. */
export function seedToSql(prompts: SeedPrompt[]): string {
  const head =
    '-- Generated by `npm run prompts:sql` from supabase/seed/prompts.json. Safe to run again.\n' +
    '-- A prompt is matched by its text, so editing the words adds a new prompt; the old one stays until you delete it.\n'
  if (prompts.length === 0) return head + '-- (no prompts in the file)\n'
  const rows = prompts.map((p) => `  (${q(p.text)}, ${q(p.depth)}, ${q(p.mood)}, ${q(p.time_of_day)}, ${q(p.track_hint)}, 'en')`)
  return (
    head +
    'insert into prompts (text, depth, mood, time_of_day, track_hint, language) values\n' +
    rows.join(',\n') +
    '\non conflict (language, (md5(text))) do update set\n' +
    '  depth = excluded.depth, mood = excluded.mood, time_of_day = excluded.time_of_day, track_hint = excluded.track_hint;\n'
  )
}

export function summarize(prompts: SeedPrompt[]): string[] {
  const count = (vals: (string | null)[], names: readonly string[]) =>
    [...names, 'any'].map((n) => `${n} ${vals.filter((v) => (n === 'any' ? v === null : v === n)).length}`).join(', ')
  return [
    `${prompts.length} prompt${prompts.length === 1 ? '' : 's'}`,
    `depth:  ${count(prompts.map((p) => p.depth), DEPTHS)}`,
    `mood:   ${count(prompts.map((p) => p.mood), MOODS)}`,
    `time:   ${count(prompts.map((p) => p.time_of_day), TIMES)}`,
    `track:  ${count(prompts.map((p) => p.track_hint), TRACK_HINTS)}`,
  ]
}
